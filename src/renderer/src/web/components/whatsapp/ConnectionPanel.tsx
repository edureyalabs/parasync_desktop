// components/whatsapp/ConnectionPanel.tsx
'use client';

import { Btn } from '@/components/account/ui';
import { C } from '@/components/account/tokens';
import { fmtDate, fmtTime } from '@/components/account/format';
import { DEVICE_NAME, RETENTION_DAYS, type WaConnection, type WaStatus } from '@/lib/whatsapp';

// The body of the WhatsApp tab's connection strip: link a number (QR), see that it is connected, disconnect or unlink it. The page owns all state and calls; this only draws it.

export interface ConnectionPanelProps {
  conn: (WaConnection & { messages_stored: number; latest_message_at: string | null }) | null;
  status: WaStatus;
  connected: boolean;
  linking: boolean;
  quiet: boolean;
  qrFresh: boolean;
  acknowledged: boolean;
  accepted: boolean;
  canLink: boolean;
  busy: string;
  confirmUnlink: boolean;
  onAccept: (v: boolean) => void;
  onConnect: () => void;
  onStop: () => void;
  onAskUnlink: (v: boolean) => void;
  onUnlink: () => void;
}

export function ConnectionPanel(p: ConnectionPanelProps) {
  const { conn, status, connected, linking, quiet, qrFresh, acknowledged, accepted, canLink, busy, confirmUnlink } = p;

  return (
    <div style={{ padding: '0.85rem 1.1rem 1rem' }}>
      {quiet && (
        <p style={{ fontSize: '0.74rem', color: C.amber, margin: '0 0 0.7rem', lineHeight: 1.5 }}>
          The WhatsApp service has not reported in for over a minute, so this may be out of date. Messages sent meanwhile are usually delivered by WhatsApp once it is back.
        </p>
      )}
      {conn?.last_error && !connected && status !== 'reconnecting' && (
        <p style={{ fontSize: '0.76rem', color: C.red, margin: '0 0 0.7rem', lineHeight: 1.5 }}>{conn.last_error}</p>
      )}

      {connected && (
        <div>
          <p style={{ fontSize: '0.78rem', color: C.soft, lineHeight: 1.6, margin: 0 }}>
            {conn?.push_name ? <><strong style={{ color: C.ink }}>{conn.push_name}</strong> · </> : null}
            connected{conn?.last_connected_at ? ` since ${fmtDate(conn.last_connected_at)} ${fmtTime(conn.last_connected_at)}` : ''} · {conn?.messages_stored ?? 0} {conn?.messages_stored === 1 ? 'message' : 'messages'} stored
            {conn?.latest_message_at ? ` (latest ${fmtDate(conn.latest_message_at)} ${fmtTime(conn.latest_message_at)})` : ''}. It shows as <strong>{DEVICE_NAME}</strong> under WhatsApp &rsaquo; Linked devices
            (a number linked before this name was set may still show <em>ParaSync</em> until it is linked again). If the link drops it reconnects on its own.
          </p>
          {confirmUnlink ? (
            <div style={{ background: C.redWash, border: `1px solid ${C.redLine}`, borderRadius: 6, padding: '0.7rem 0.9rem', marginTop: '0.8rem' }}>
              <p style={{ fontSize: '0.78rem', color: C.ink, lineHeight: 1.55, margin: '0 0 0.6rem' }}>
                <strong>Unlink this number?</strong> The {DEVICE_NAME} device is removed from the phone, and everything stored for it (chats, messages, attachments, sent history) is deleted now. This cannot be undone.
              </p>
              <div style={{ display: 'flex', gap: '0.5rem' }}>
                <Btn size="sm" variant="primary" onClick={p.onUnlink} disabled={!!busy}>{busy === 'unlink' ? 'Unlinking…' : 'Unlink and delete'}</Btn>
                <Btn size="sm" variant="ghost" onClick={() => p.onAskUnlink(false)} disabled={!!busy}>Keep it linked</Btn>
              </div>
            </div>
          ) : (
            <div style={{ display: 'flex', gap: '0.5rem', flexWrap: 'wrap', marginTop: '0.8rem' }}>
              <Btn size="sm" onClick={p.onStop} disabled={!!busy}>{busy === 'stop' ? 'Disconnecting…' : 'Disconnect'}</Btn>
              <Btn size="sm" variant="ghost" onClick={() => p.onAskUnlink(true)} disabled={!!busy}>Unlink…</Btn>
            </div>
          )}
        </div>
      )}

      {status === 'reconnecting' && (
        <p style={{ fontSize: '0.8rem', color: C.body, lineHeight: 1.55, margin: 0 }}>
          The link dropped and is reconnecting on its own{conn && conn.reconnect_streak > 0 ? ` (attempt ${conn.reconnect_streak})` : ''}; you do not need to press anything. If the phone has been offline for about two weeks, WhatsApp may ask you to link again.
        </p>
      )}

      {linking && (
        <div>
          {conn?.qr_data_url ? (
            <div style={{ display: 'flex', gap: '1.1rem', flexWrap: 'wrap', alignItems: 'center' }}>
              {/* eslint-disable-next-line @next/next/no-img-element -- a data URL generated by the gateway; nothing to optimise */}
              <img src={conn.qr_data_url} alt="WhatsApp link QR code" width={190} height={190} style={{ border: `1px solid ${C.line}`, borderRadius: 8, background: '#fff', opacity: qrFresh ? 1 : 0.35 }} />
              <ol style={{ margin: 0, paddingLeft: '1.05rem', fontSize: '0.8rem', color: C.body, lineHeight: 1.85, maxWidth: 340 }}>
                <li>Open WhatsApp on the phone.</li>
                <li>Settings &rsaquo; Linked devices &rsaquo; <strong>Link a device</strong>.</li>
                <li>Scan this code.</li>
                {!qrFresh && <li style={{ color: C.amber }}>This code expired; a new one is coming.</li>}
              </ol>
            </div>
          ) : (
            <p style={{ fontSize: '0.8rem', color: C.soft, margin: 0 }}>Waiting for WhatsApp to issue a code…</p>
          )}
          <div style={{ marginTop: '0.7rem' }}><Btn size="sm" variant="ghost" onClick={p.onStop} disabled={!!busy}>Cancel</Btn></div>
        </div>
      )}

      {!linking && !connected && status !== 'reconnecting' && (
        <div>
          <p style={{ fontSize: '0.74rem', color: C.soft, lineHeight: 1.55, margin: '0 0 0.7rem' }}>
            This links the number the way WhatsApp Web does. WhatsApp can restrict numbers it sees being automated, so use a business number, and use it responsibly: no spam or bulk
            messages. Only chats you open are stored, for {RETENTION_DAYS} days. Once linked, the connection is kept alive and restored automatically until you disconnect, unlink, or switch the WhatsApp tool off.
          </p>
          <div style={{ display: 'flex', alignItems: 'center', gap: '1rem', flexWrap: 'wrap' }}>
            {!acknowledged && (
              <label style={{ display: 'flex', gap: '0.45rem', alignItems: 'center', fontSize: '0.78rem', color: C.ink, cursor: 'pointer' }}>
                <input type="checkbox" checked={accepted} onChange={e => p.onAccept(e.target.checked)} />
                I understand
              </label>
            )}
            <Btn variant="primary" size="sm" onClick={p.onConnect} disabled={!canLink || !!busy}>{busy === 'connect' ? 'Starting…' : 'Connect'}</Btn>
          </div>
        </div>
      )}
    </div>
  );
}
